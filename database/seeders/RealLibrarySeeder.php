            'Ветер принёс запах моря и далёких путешествий.',
            'Она посмотрела в окно и впервые за долгое время улыбнулась.',
            'Тишина была такой глубокой, что казалась частью разговора.',
        ];

        $middles = [
            'Каждое решение давалось тяжело, но отступать было поздно.',
            'Он вспомнил слова, сказанные когда-то давно, и они вдруг обрели новый смысл.',
            'Вокруг всё казалось знакомым, однако что-то важное изменилось навсегда.',
            'Разговор шёл о простых вещах, но за ними угадывалось нечто большее.',
            'Надо было выбрать одну дорогу, и этот выбор пугал своей окончательностью.',
            'Прошлое возвращалось обрывками воспоминаний, не желая отпускать.',
            'В этом месте время текло иначе, чем в остальном мире.',
            'Он давно привык к одиночеству, но сегодня оно ощущалось особенно остро.',
            'Люди вокруг спешили жить, не замечая чужих сомнений.',
            'Казалось, что сама земля помнит всё, что здесь произошло.',
        ];

        $closers = [
            'И всё же он сделал шаг вперёд.',
            'Ответ пришёл не сразу, но пришёл.',
            'Они расстались, чтобы однажды встретиться снова.',
            'С этого момента всё пошло по-другому.',
            'Ночь опустилась на город, укрыв его тайны.',
            'Он понял, что назад дороги нет — и не пожалел об этом.',
            'Наступило утро, и вместе с ним пришла новая надежда.',
            'Она унесла с собой вопрос, на который никто не смог ответить.',
            'Тишина снова заполнила комнату, но теперь она была иной.',
            'Путь продолжался, и это было главное.',
        ];

        $paragraphs = [];

        for ($i = 0; $i < 4; $i++) {
            $sentence = $openers[array_rand($openers)] . ' '
                . $middles[array_rand($middles)] . ' '
                . $closers[array_rand($closers)];

            if ($i === 0) {
                $sentence .= ' Так начинается одна из глав «' . $bookTitle . '».';
            }

            if ($i === 2) {
                $sentence .= ' В этом месте повествования особенно ясно чувствуется голос ' . $author . '.';
            }

            $paragraphs[] = $sentence;
        }

        $paragraphs[] = sprintf(
            'Глава %d, страница %d: история продолжается, оставляя читателю пространство для собственных мыслей.',
            $chapter,
            $page
        );

        return implode("\n\n", $paragraphs);
    }

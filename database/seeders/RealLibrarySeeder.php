    public function run(): void
    {
        $this->call(RoleSystemSeeder::class);

        $admin = User::create([
            'name' => 'Администратор',
            'email' => 'admin@gmail.com',
            'password' => 'admin',
            'about' => 'Администратор библиотеки Libraria.',
        ]);
        $admin->assignRole(User::ROLE_ADMIN);

        $reader = User::create([
            'name' => 'Читатель',
            'email' => 'reader@libraria.local',
            'password' => 'reader',
            'about' => 'Читаю классику, фантастику и всё, что попадётся под руку.',
        ]);
        $reader->assignRole(User::ROLE_READER);

        $categoryNames = [
            'Классика', 'Роман', 'Фантастика', 'Антиутопия', 'Магический реализм',
            'Драма', 'Поэзия', 'Приключения', 'История', 'Комедия', 'Философия', 'Фэнтези',
        ];

        $categories = [];
        foreach ($categoryNames as $name) {
            $categories[$name] = Category::create(['name' => $name]);
        }

        $authors = $this->authors();

        DB::transaction(function () use ($authors, $categories) {
            $bookIndex = 0;

            foreach ($authors as $authorData) {
                $author = User::create([
                    'name' => $authorData['name'],
                    'email' => $authorData['email'],
                    'password' => 'author',
                    'about' => $authorData['bio'],
                    'city' => $authorData['city'] ?? null,
                ]);
                $author->assignRole(User::ROLE_AUTHOR);

                foreach ($authorData['books'] as $bookData) {
                    $book = Book::create([
                        'title' => $bookData['title'],
                        'author' => $authorData['name'],
                        'description' => $bookData['description'],
                        'user_id' => $author->id,
                        'author_bio' => $authorData['bio'],
                        'language' => 'ru',
                        'rating' => random_int(40, 50) / 10,
                        'is_published' => true,
                        'comments_count' => 0,
                        'likes_count' => random_int(5, 400),
                        'views_count' => random_int(100, 6000),
                    ]);

                    $book->categories()->attach(
                        collect($bookData['categories'])
                            ->map(fn ($name) => $categories[$name]->id)
                            ->unique()
                            ->values()
                            ->all()
                    );

                    $chaptersCount = 8 + ($bookIndex % 5);
                    $totalPages = 0;

                    for ($chapterNumber = 1; $chapterNumber <= $chaptersCount; $chapterNumber++) {
                        $chapter = Chapter::create([
                            'book_id' => $book->id,
                            'title' => 'Глава ' . $chapterNumber,
                            'content' => '',
                            'number' => $chapterNumber,
                            'characters' => null,
                            'images' => null,
                            'comments_count' => 0,
                            'likes_count' => random_int(0, 60),
                            'views_count' => random_int(10, 900),
                        ]);

                        $pagesCount = 3 + (($chapterNumber + $bookIndex) % 4);
                        $firstPageContent = '';

                        for ($pageNumber = 1; $pageNumber <= $pagesCount; $pageNumber++) {
                            $content = $this->pageContent(
                                $authorData['name'],
                                $bookData['title'],
                                $chapterNumber,
                                $pageNumber
                            );

                            Page::create([
                                'chapter_id' => $chapter->id,
                                'title' => null,
                                'content' => $content,
                                'number' => $pageNumber,
                            ]);

                            if ($pageNumber === 1) {
                                $firstPageContent = $content;
                            }
                        }

                        $chapter->update(['content' => $firstPageContent]);
                        $totalPages += $pagesCount;
                    }

                    $book->update(['number_of_pages' => $totalPages]);
                    $bookIndex++;
                }
            }
        });

        $this->command?->info(sprintf(
            'Библиотека заполнена: %d авторов, %d книг, %d глав, %d страниц.',
            count($authors),
            Book::count(),
            Chapter::count(),
            Page::count()
        ));
    }

